class VisualService:
    def __init__(self):
        pass

    def get_dimensions(self, aspect_ratio: str, draft: bool = False) -> Tuple[int, int]:
        """Returns (width, height) for the chosen aspect ratio and quality mode."""
        resolutions = {
            "9:16": (1080, 1920),
            "16:9": (1920, 1080),
            "1:1": (1080, 1080),
            "4:5": (1080, 1350)
        }
        w, h = resolutions.get(aspect_ratio, (1080, 1920))
        if draft:
            return (w // 2, h // 2)
        return (w, h)

    def generate_html_scene(
        self,
        storyboard: Dict[str, Any],
        narration_timing: List[Dict[str, Any]],
        style_slug: str,
        aspect_ratio: str,
        output_html_path: str,
        subtitles_enabled: bool = True
    ) -> str:
        """
        Generates a rich, cinematic, code-animated visual world
        where EVERY SINGLE SHOT renders a distinct scene component with
        active camera movements, character host animations, realistic interfaces,
        and strict style-specific aesthetics (Swiss Motion vs Blueprint vs Dark Keynote).
        """
        os.makedirs(os.path.dirname(output_html_path), exist_ok=True)
        w, h = self.get_dimensions(aspect_ratio, draft=False)

        # Resolve complete style specification
        style_spec = style_service.resolve_style_spec(style_slug)
        brand_keys = storyboard.get("brand_keys", [])

        # Fetch relevant brand SVG icons
        brand_svgs = {}
        for bk in brand_keys[:4]:
            svg_content = brand_service.get_brand_svg(bk, size=38)
            if svg_content:
                brand_svgs[bk] = svg_content

        # Calculate exact total duration
        if narration_timing:
            total_duration = max(sc.get("end_time", 0.0) for sc in narration_timing) + 0.8
        else:
            total_duration = float(storyboard.get("total_target_duration", 45))

        # Build scene timeline array
        scenes_data = []
        events_data = []
        scenes_list = storyboard.get("scenes", [])

        for i, sc in enumerate(scenes_list):
            timing = narration_timing[i] if i < len(narration_timing) else {}
            start_t = timing.get("start_time", i * (total_duration / max(1, len(scenes_list))))
            end_t = timing.get("end_time", (i + 1) * (total_duration / max(1, len(scenes_list))))
